import { PLATFORM_RELEASE } from "../../../supabase/functions/_shared/platformRelease";
import { PLUGIN_REGISTRY } from "../../../cpr/plugins/registry";
import { DEPENDENCY_DOCTRINE } from "../../../supabase/functions/_shared/dependencyDoctrine";

function pluginTable(): string {
  return Object.entries(PLUGIN_REGISTRY)
    .slice(0, 80)
    .map(([key, entry]: [string, any]) => {
      const pkgs = [entry.npm, ...(entry.companions || [])].filter(Boolean).join(", ");
      return `  - ${key}: ${pkgs}`;
    })
    .join("\n");
}

export function getPlatformContext(): string {
  const r = PLATFORM_RELEASE;
  return `# NativeForge Platform Context (release ${r.id})

## Canonical project structure
The canonical project is the FRONTEND root that CPR detected (backend/server folders are
excluded from the build). Inside it:
  package.json               — single source of truth for dependencies
  vite.config.ts             — web build config; output must land in dist/
  capacitor.config.json      — Capacitor config, generated/normalized by CPR
  src/**                     — application source
  android/                   — generated native Android project
    android/app/src/main/    — AndroidManifest.xml, java|kotlin, res/
    android/app/build.gradle, android/build.gradle, android/variables.gradle
  ios/App/App/               — generated native iOS project (Info.plist)

## capacitor.config.json — required fields
  appId       reverse-DNS bundle id, must match android applicationId
  appName     display name
  webDir      "dist" for Vite projects (never "www" unless the build emits www)
  bundledWebRuntime  false
  server.androidScheme  "https"
  plugins     per-plugin config objects, keys are the Capacitor plugin class names

## Platform standard versions (do not deviate)
  Node ${r.nodeVersion}            npm ${r.npmVersion}
  Capacitor ${r.capacitorVersion} (major ${r.capacitorMajor}) — every @capacitor/* package
                     must use this EXACT version, no ranges
  Gradle ${r.gradleVersion}        Android Gradle Plugin ${r.agpVersion}
  JDK ${r.jdkVersion}              compileSdk ${r.compileSdk}  targetSdk ${r.targetSdk}  minSdk ${r.minSdk}
  TypeScript 5.x     Vite 5.x

## Plugin registry — correct package names
${pluginTable()}

## Display mode Android resource requirements
  Edge-to-edge / immersive modes require:
    android/app/src/main/res/values/styles.xml with the AppTheme.NoActionBar parent
    android:windowLayoutInDisplayCutoutMode=shortEdges on API 28+
    android/app/src/main/res/values-v31/ for splash-screen theme attributes
    A matching <style> entry for every display mode referenced by the manifest
  Splash assets live under res/drawable* and res/values/colors.xml (colorPrimary,
  splashBackground). A missing colors.xml entry is a common Gradle failure.

## Build pipeline steps the agent may re-verify
  install         dependency install in the canonical root
  build           web build (vite build)
  capacitor_sync  npx cap sync android
  gradle_build    ./gradlew assembleDebug|assembleRelease

## Hard rules
  - .github/workflows/** and cpr/** are PLATFORM-OWNED. Never modify them.
  - .env* is managed by the structured environment variable system.
  - Lockfiles are regenerated by the pipeline; never hand-edit them.
  - Never change what a component does. Only fix what breaks the build.

## Dependency doctrine
${DEPENDENCY_DOCTRINE}`;
}