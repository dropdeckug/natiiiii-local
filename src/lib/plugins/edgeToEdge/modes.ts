/**
 * Edge-to-Edge has three distinct usages. The user picks one in the Plugins
 * panel; the choice is persisted as the `EDGE_TO_EDGE_MODE` plugin secret and
 * drives BOTH the deterministic wiring (this module + ./index.ts) and the AI
 * wiring prompt, so the Action Panel only reports what the user actually chose.
 */

export type EdgeToEdgeMode = "spacer-fade" | "status-bar-tint" | "native-ready";

export const DEFAULT_EDGE_TO_EDGE_MODE: EdgeToEdgeMode = "spacer-fade";

export interface EdgeToEdgeModeSpec {
  id: EdgeToEdgeMode;
  label: string;
  tagline: string;
  description: string;
  bestFor: string;
  /** Draw the WebView behind the system bars (WindowCompat decorFitsSystemWindows=false). */
  drawsBehindBars: boolean;
  /** Inject the translucent top spacer with a fade. */
  injectsSpacer: boolean;
  /** Tint the native status bar to the app background instead of overlaying. */
  tintsStatusBar: boolean;
}

export const EDGE_TO_EDGE_MODES: EdgeToEdgeModeSpec[] = [
  {
    id: "spacer-fade",
    label: "Safe spacer + fade",
    tagline: "For websites never designed for edge-to-edge",
    description:
      "Draws behind the system bars, then adds a top spacer exactly the height of the status bar. The spacer is painted with the app's own background colour (re-read at runtime, so it follows light/dark mode) and fades out into the content below — the modern look. Content is pushed down so nothing hides under the status bar. The gesture/navigation area gets a matching bottom inset only when the device reports one, so swipe-navigation phones stay full-bleed.",
    bestFor: "Converted websites, dashboards, any UI with a fixed top bar.",
    drawsBehindBars: true,
    injectsSpacer: true,
    tintsStatusBar: false,
  },
  {
    id: "status-bar-tint",
    label: "Tinted status bar",
    tagline: "Keep the bars, match their colour",
    description:
      "Leaves the system bars in place (no draw-behind) and instead paints the status bar and navigation bar with your app's background colour. NativeBridge generates values/colors.xml and values-night/colors.xml plus the matching styles so the bars flip automatically when the device switches to dark mode.",
    bestFor: "Apps that want a classic, opaque chrome that still matches the theme.",
    drawsBehindBars: false,
    injectsSpacer: false,
    tintsStatusBar: true,
  },
  {
    id: "native-ready",
    label: "Already edge-to-edge",
    tagline: "The app handles its own insets",
    description:
      "For layouts already built for edge-to-edge. NativeBridge only does the native minimum: transparent bars, draw-behind, viewport-fit=cover and the safe-area CSS variables. No spacer and no padding is injected, so your existing insets keep working untouched.",
    bestFor: "Apps already using env(safe-area-inset-*) or a native design system.",
    drawsBehindBars: true,
    injectsSpacer: false,
    tintsStatusBar: false,
  },
];

export function getEdgeToEdgeMode(mode?: string | null): EdgeToEdgeModeSpec {
  return (
    EDGE_TO_EDGE_MODES.find((m) => m.id === mode) ??
    EDGE_TO_EDGE_MODES.find((m) => m.id === DEFAULT_EDGE_TO_EDGE_MODE)!
  );
}

