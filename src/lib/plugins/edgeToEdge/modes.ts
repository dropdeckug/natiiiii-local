/**
 * Runtime spacer module. Reads the real page background (body / #root / theme
 * meta) every time the theme changes and paints a status-bar-height spacer
 * with a fade, then offsets the app so no content sits under the status bar.
 */
export const EDGE_TO_EDGE_SPACER_TS = `// Auto-generated by NativeBridge — Edge-to-Edge safe spacer.
// Adds a status-bar-height spacer painted with the app's own background
// colour and faded into the content below. Colour is re-read whenever the
// theme changes so light/dark mode both look correct.
import { Capacitor } from "@capacitor/core";

const SPACER_ID = "nb-status-bar-spacer";
const STYLE_ID = "nb-status-bar-spacer-style";

function readAppBackground(): string {
  const probe: (Element | null)[] = [
    document.querySelector("[data-status-bar-probe]"),
    document.getElementById("root"),
    document.getElementById("__next"),
    document.body,
    document.documentElement,
  ];
  for (const el of probe) {
    if (!el) continue;
    const bg = getComputedStyle(el).backgroundColor;
    if (bg && bg !== "transparent" && !/rgba\\(0,\\s*0,\\s*0,\\s*0\\)/.test(bg)) return bg;
  }
  return window.matchMedia?.("(prefers-color-scheme: dark)").matches ? "#0b0b0f" : "#ffffff";
}

function ensureStyle() {
  if (document.getElementById(STYLE_ID)) return;
  const style = document.createElement("style");
  style.id = STYLE_ID;
  style.textContent = [
    "#" + SPACER_ID + "{position:fixed;top:0;left:0;right:0;z-index:2147483646;",
    "height:calc(env(safe-area-inset-top, 0px) + 2px);pointer-events:none;",
    "-webkit-backdrop-filter:saturate(180%) blur(12px);backdrop-filter:saturate(180%) blur(12px);",
    "transition:background 200ms ease;}",
    ":where(html){--nb-status-bar-height:env(safe-area-inset-top, 0px);}",
    ":where(body){padding-top:var(--nb-status-bar-height);}",
    "@supports (padding: max(0px)) { :where(body){padding-bottom:env(safe-area-inset-bottom, 0px);} }",
  ].join("");
  document.head.appendChild(style);
}

function paint() {
  const bg = readAppBackground();
  const el = document.getElementById(SPACER_ID);
  if (!el) return;
  // Solid at the very top (under the clock/battery), fading into the content.
  el.style.background =
    "linear-gradient(to bottom, " + bg + " 0%, " + bg + " 62%, transparent 100%)";
}

export function initStatusBarSpacer() {
  if (!Capacitor.isNativePlatform()) return;
  ensureStyle();
  if (!document.getElementById(SPACER_ID)) {
    const el = document.createElement("div");
    el.id = SPACER_ID;
    el.setAttribute("aria-hidden", "true");
    document.body.appendChild(el);
  }
  paint();

  const schedule = () => requestAnimationFrame(paint);
  const observer = new MutationObserver(schedule);
  observer.observe(document.documentElement, { attributes: true, attributeFilter: ["class", "style", "data-theme"] });
  observer.observe(document.body, { attributes: true, attributeFilter: ["class", "style", "data-theme"] });
  window.matchMedia?.("(prefers-color-scheme: dark)").addEventListener?.("change", schedule);
  window.addEventListener("popstate", schedule);
}

if (typeof window !== "undefined") {
  if (document.readyState === "loading") {
    window.addEventListener("DOMContentLoaded", () => initStatusBarSpacer());
  } else {
    initStatusBarSpacer();
  }
}
`;

