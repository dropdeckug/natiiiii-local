/**
 * Edge-to-Edge plugin wiring (Capacitor 6+ / Android).
 *
 * Produces every file change required to:
 *   1. Draw the WebView under the status & navigation bars (true native edge-to-edge).
 *   2. Keep status-bar icons readable as the page background changes
 *      (dynamic light/dark icons via Capacitor StatusBar).
 *   3. Expose safe-area-inset-* as CSS variables so the user's layout
 *      can respect notches and the gesture pill.
 *
 * Exposes a single `wireEdgeToEdge(...)` entry that returns a list of
 * patches + npm deps + permissions. The build pipeline applies these to
 * the in-memory ProjectFile tree, identical to other plugin generators.
 *
 * Important: we do NOT install the deprecated @capacitor/edge-to-edge plugin,
 * and we do not depend on any edge-to-edge plugin for the native draw-behind
 * behavior. NativeBridge patches MainActivity.java directly with
 * WindowCompat.setDecorFitsSystemWindows(getWindow(), false) after
 * super.onCreate(savedInstanceState), which is the stable native requirement.
 */

import type { ProjectFile } from "@/stores/projectStore";
import {
  type EdgeToEdgeMode,
  DEFAULT_EDGE_TO_EDGE_MODE,
  getEdgeToEdgeMode,
  EDGE_TO_EDGE_SPACER_TS,
  EDGE_TO_EDGE_COLORS_XML,
  EDGE_TO_EDGE_COLORS_NIGHT_XML,
  TINTED_STYLES_XML,
  TINTED_STYLES_NIGHT_XML,
  SAFE_AREA_VARS_CSS,
  SAFE_AREA_PADDED_CSS,
} from "./modes";

export type { EdgeToEdgeMode };

export interface EdgeToEdgePatch {
  path: string;
  op: "create" | "patch";
  content: string;
  reason: string;
}

export interface EdgeToEdgeWiring {
  npmDeps: string[];
  patches: EdgeToEdgePatch[];
  warnings: string[];
  mode?: EdgeToEdgeMode;
}


const flatten = (files: ProjectFile[]): ProjectFile[] => {
  const out: ProjectFile[] = [];
  const walk = (nodes: ProjectFile[]) => {
    for (const n of nodes) {
      out.push(n);
      if (n.children) walk(n.children);
    }
  };
  walk(files);
  return out;
};

const findEntryFile = (files: ProjectFile[]): ProjectFile | null => {
  const flat = flatten(files);
  const candidates = [
    "src/main.tsx",
    "src/main.ts",
    "src/index.tsx",
    "src/index.ts",
    "src/main.jsx",
    "src/main.js",
  ];
  for (const c of candidates) {
    const hit = flat.find(f => f.type === "file" && (f.path === c || f.path.endsWith(`/${c}`)));
    if (hit) return hit;
  }
  return null;
};

/* ───────────── Runtime modules injected into the user's web app ───────────── */

export const EDGE_TO_EDGE_RUNTIME_TS = `// Auto-generated by NativeBridge — Edge-to-Edge runtime.
// Detects the page background and flips status-bar icons (light/dark) so
// they stay readable. Also enables WebView overlay so the app draws
// behind the status/navigation bars.
import { Capacitor } from "@capacitor/core";
import { StatusBar, Style } from "@capacitor/status-bar";

const RGB_RE = /rgba?\\(([^)]+)\\)/;

function parseColor(c: string): { r: number; g: number; b: number; a: number } | null {
  const m = c.match(RGB_RE);
  if (!m) return null;
  const parts = m[1].split(",").map(v => parseFloat(v.trim()));
  const [r, g, b] = parts;
  const a = parts.length >= 4 ? parts[3] : 1;
  if ([r, g, b].some(n => Number.isNaN(n))) return null;
  return { r, g, b, a: Number.isNaN(a) ? 1 : a };
}

function pickProbeColor(): { r: number; g: number; b: number } | null {
  const htmlAttr = document.documentElement.getAttribute("data-status-bar");
  if (htmlAttr === "light") return { r: 0, g: 0, b: 0 };
  if (htmlAttr === "dark") return { r: 255, g: 255, b: 255 };

  const themeMeta = document.querySelector('meta[name="theme-color"]') as HTMLMetaElement | null;
  if (themeMeta?.content) {
    const probe = document.createElement("span");
    probe.style.color = themeMeta.content;
    document.body.appendChild(probe);
    const parsed = parseColor(getComputedStyle(probe).color);
    probe.remove();
    if (parsed && parsed.a > 0.05) return parsed;
  }

  const x = Math.max(1, Math.floor(window.innerWidth / 2));
  const candidates: (Element | null)[] = [
    document.querySelector("[data-status-bar-probe]"),
    document.elementFromPoint(x, 4),
    document.elementFromPoint(x, 12),
    document.getElementById("root"),
    document.getElementById("__next"),
    document.body,
    document.documentElement,
  ];
  for (const el of candidates) {
    if (!el) continue;
    const parsed = parseColor(getComputedStyle(el).backgroundColor);
    if (parsed && parsed.a > 0.05) return parsed;
  }
  return null;
}

function isDarkBg(): boolean {
  const c = pickProbeColor();
  if (!c) return window.matchMedia?.("(prefers-color-scheme: dark)").matches ?? false;
  const toLin = (v: number) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  };
  const L = 0.2126 * toLin(c.r) + 0.7152 * toLin(c.g) + 0.0722 * toLin(c.b);
  return L < 0.5;
}

let lastStyle: Style | null = null;
async function syncStatusBar() {
  if (!Capacitor.isNativePlatform()) return;
  try {
    const next = isDarkBg() ? Style.Light : Style.Dark;
    if (next === lastStyle) return;
    lastStyle = next;
    await StatusBar.setStyle({ style: next });
  } catch (e) {
    console.warn("[edge-to-edge] setStyle failed:", e);
  }
}

function scheduleSync() {
  requestAnimationFrame(() => { void syncStatusBar(); });
}

export async function initEdgeToEdge() {
  if (!Capacitor.isNativePlatform()) return;
  try {
    await StatusBar.setOverlaysWebView({ overlay: true });
    await StatusBar.setBackgroundColor({ color: "#00000000" });
  } catch (e) {
    console.warn("[edge-to-edge] overlay setup failed:", e);
  }
  await syncStatusBar();

  const observer = new MutationObserver(scheduleSync);
  observer.observe(document.body, { attributes: true, attributeFilter: ["class", "style", "data-theme", "data-status-bar"] });
  observer.observe(document.documentElement, { attributes: true, attributeFilter: ["class", "style", "data-theme", "data-status-bar"] });
  if (document.head) new MutationObserver(scheduleSync).observe(document.head, { childList: true, subtree: true, attributes: true });

  window.matchMedia?.("(prefers-color-scheme: dark)").addEventListener?.("change", scheduleSync);
  window.addEventListener("popstate", scheduleSync);

  const wrap = (key: "pushState" | "replaceState") => {
    const orig = history[key];
    history[key] = function (...args: any[]) {
      const ret = orig.apply(this, args as any);
      scheduleSync();
      return ret;
    } as any;
  };
  wrap("pushState"); wrap("replaceState");
}

if (typeof window !== "undefined") {
  if (document.readyState === "complete" || document.readyState === "interactive") {
    void initEdgeToEdge();
  } else {
    window.addEventListener("DOMContentLoaded", () => { void initEdgeToEdge(); });
  }
}
`;

