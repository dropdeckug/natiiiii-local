/**
 * Mode 2/3/4/5 — reads the real body background, computes relative luminance
 * and drives the native bars. Re-runs on DOM mutation, system theme change and
 * app resume.
 */
export function colorMatchingModule(cfg: DisplayModeConfig, spec: DisplayModeSpec): string {
  return `// Auto-generated by NativeForge Display Mode — runtime colour matching.
import { Capacitor } from "@capacitor/core";
import { StatusBar, Style } from "@capacitor/status-bar";
import { App } from "@capacitor/app";

const OVERLAYS = ${spec.overlaysWebView};
const LIGHT_FALLBACK = "${cfg.lightStatusBarColor}";
const DARK_FALLBACK = "${cfg.darkStatusBarColor}";

function toHex(rgb: string, fallback: string): { hex: string; luminance: number } {
  const m = rgb.match(/rgba?\\(([^)]+)\\)/);
  let r: number, g: number, b: number, a = 1;
  if (m) {
    const parts = m[1].split(",").map((v) => parseFloat(v.trim()));
    [r, g, b] = parts;
    if (parts.length >= 4) a = parts[3];
  } else {
    const f = fallback.replace("#", "");
    r = parseInt(f.slice(0, 2), 16);
    g = parseInt(f.slice(2, 4), 16);
    b = parseInt(f.slice(4, 6), 16);
  }
  if ([r, g, b].some((n) => Number.isNaN(n)) || a < 0.05) {
    return toHex("", fallback);
  }
  const lin = (v: number) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  };
  const luminance = 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
  const hx = (n: number) => Math.round(n).toString(16).padStart(2, "0");
  return { hex: "#" + hx(r) + hx(g) + hx(b), luminance };
}

function readBackground(): { hex: string; luminance: number } {
  const prefersDark = window.matchMedia?.("(prefers-color-scheme: dark)").matches ?? false;
  const fallback = prefersDark ? DARK_FALLBACK : LIGHT_FALLBACK;
  const probes: (Element | null)[] = [
    document.querySelector("[data-nf-color-probe]"),
    document.body,
    document.getElementById("root"),
    document.getElementById("__next"),
    document.documentElement,
  ];
  for (const el of probes) {
    if (!el) continue;
    const bg = window.getComputedStyle(el).backgroundColor;
    if (bg && bg !== "transparent" && !/rgba\\(0,\\s*0,\\s*0,\\s*0\\)/.test(bg)) {
      return toHex(bg, fallback);
    }
  }
  return toHex("", fallback);
}

let last = "";

export async function syncDisplayMode(): Promise<void> {
  if (!Capacitor.isNativePlatform()) return;
  const { hex, luminance } = readBackground();
  const isLightBackground = luminance > 0.5;
  document.documentElement.setAttribute("data-nf-scheme", isLightBackground ? "light" : "dark");
  const signature = hex + (isLightBackground ? "-d" : "-l") + (document.body.dataset.nfFullscreen || "");
  if (signature === last) return;
  last = signature;
  try {
    await StatusBar.setStyle({ style: isLightBackground ? Style.Dark : Style.Light });
    if (!OVERLAYS && document.body.dataset.nfFullscreen !== "true") {
      await StatusBar.setBackgroundColor({ color: hex });
    } else {
      await StatusBar.setBackgroundColor({ color: "#00000000" });
    }
  } catch (e) {
    console.warn("[nf-display-mode] status bar update failed", e);
  }
  try {
    const nav = (window as any).NavigationBar;
    if (nav?.setColor) await nav.setColor({ color: hex, darkButtons: isLightBackground });
  } catch { /* NavigationBar plugin is optional */ }
}

const schedule = () => requestAnimationFrame(() => { void syncDisplayMode(); });

export async function initDisplayMode(): Promise<void> {
  if (!Capacitor.isNativePlatform()) return;
  try {
    await StatusBar.setOverlaysWebView({ overlay: OVERLAYS });
  } catch (e) {
    console.warn("[nf-display-mode] overlay setup failed", e);
  }
  await syncDisplayMode();

  new MutationObserver(schedule).observe(document.body, {
    attributes: true,
    attributeFilter: ["style", "class", "data-theme", "data-nf-fullscreen"],
  });
  new MutationObserver(schedule).observe(document.documentElement, {
    attributes: true,
    attributeFilter: ["style", "class", "data-theme"],
  });

  window.matchMedia?.("(prefers-color-scheme: dark)").addEventListener?.("change", schedule);
  window.addEventListener("resize", schedule);
  window.addEventListener("orientationchange", schedule);
  window.addEventListener("popstate", schedule);

  try {
    App.addListener("appStateChange", ({ isActive }) => { if (isActive) schedule(); });
  } catch { /* @capacitor/app not available */ }
}

if (typeof window !== "undefined") {
  if (document.readyState === "loading") {
    window.addEventListener("DOMContentLoaded", () => { void initDisplayMode(); });
  } else {
    void initDisplayMode();
  }
}
`;
}

/** Mode 4 — injects and themes the two frosted glass layers. */
export const GLASS_MODULE_TS = `// Auto-generated by NativeForge Display Mode — glassmorphism layers.
import { Capacitor } from "@capacitor/core";
import "./display-mode-glass.css";

function ensureLayer(id: string): HTMLElement {
  let el = document.getElementById(id);
  if (!el) {
    el = document.createElement("div");
    el.id = id;
    el.setAttribute("aria-hidden", "true");
    document.body.appendChild(el);
  }
  return el;
}

function applyScheme() {
  const dark = document.documentElement.getAttribute("data-nf-scheme") === "dark"
    || (window.matchMedia?.("(prefers-color-scheme: dark)").matches ?? false);
  const tint = dark ? "rgba(0, 0, 0, 0.7)" : "rgba(255, 255, 255, 0.7)";
  for (const id of ["nf-glass-top", "nf-glass-bottom"]) {
    const el = document.getElementById(id);
    if (el) el.style.backgroundColor = tint;
  }
}

export function initGlassLayers(): void {
  if (!Capacitor.isNativePlatform()) return;
  ensureLayer("nf-glass-top");
  ensureLayer("nf-glass-bottom");
  applyScheme();
  window.matchMedia?.("(prefers-color-scheme: dark)").addEventListener?.("change", applyScheme);
  new MutationObserver(applyScheme).observe(document.documentElement, {
    attributes: true,
    attributeFilter: ["data-nf-scheme", "class", "data-theme"],
  });
}

if (typeof window !== "undefined") {
  if (document.readyState === "loading") {
    window.addEventListener("DOMContentLoaded", initGlassLayers);
  } else {
    initGlassLayers();
  }
}
`;

/** Mode 5 — the public per-page API used by the injected hooks. */
export const PER_PAGE_API_TS = `// Auto-generated by NativeForge Display Mode — per-page full screen API.
import { Capacitor } from "@capacitor/core";
import { StatusBar, Style } from "@capacitor/status-bar";
import { syncDisplayMode } from "./display-mode";

interface Saved { paddingTop: string; paddingBottom: string; }
let saved: Saved | null = null;
let depth = 0;

/** Switch the current page to true full screen (content under both bars). */
export async function enterFullScreen(iconStyle: "LIGHT" | "DARK" = "LIGHT"): Promise<void> {
  depth += 1;
  if (depth > 1) return;
  if (!saved) {
    saved = {
      paddingTop: document.body.style.paddingTop,
      paddingBottom: document.body.style.paddingBottom,
    };
  }
  document.body.dataset.nfFullscreen = "true";
  document.body.style.paddingTop = "0px";
  document.body.style.paddingBottom = "0px";
  if (!Capacitor.isNativePlatform()) return;
  try {
    await StatusBar.setOverlaysWebView({ overlay: true });
    await StatusBar.setBackgroundColor({ color: "#00000000" });
    await StatusBar.setStyle({ style: iconStyle === "LIGHT" ? Style.Light : Style.Dark });
  } catch (e) {
    console.warn("[nf-display-mode] enterFullScreen failed", e);
  }
}

/** Restore the base display mode configured for the project. */
export async function exitFullScreen(): Promise<void> {
  depth = Math.max(0, depth - 1);
  if (depth > 0) return;
  delete document.body.dataset.nfFullscreen;
  if (saved) {
    document.body.style.paddingTop = saved.paddingTop;
    document.body.style.paddingBottom = saved.paddingBottom;
    saved = null;
  }
  await syncDisplayMode();
}

/** React helper: call inside a component that should be full screen. */
export function useFullScreenPage(iconStyle: "LIGHT" | "DARK" = "LIGHT") {
  if (typeof window === "undefined") return;
  void enterFullScreen(iconStyle);
  return () => { void exitFullScreen(); };
}
`;

