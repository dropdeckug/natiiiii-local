/**
 * File templates emitted by the Display Mode plugin.
 *
 * Every template is deterministic: the same config always produces the same
 * bytes, so re-running the wiring step is idempotent.
 */

import type { DisplayModeConfig, DisplayModeSpec } from "./registry";

const TRANSPARENT = "#00000000";

const header = (what: string) =>
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Auto-generated by NativeForge Display Mode — ${what}. Do not edit by hand. -->`;

interface ThemeVars {
  statusBarColor: string;
  navigationBarColor: string;
  lightStatusIcons: boolean; // windowLightStatusBar (true = dark icons)
  lightNavIcons: boolean;
  edgeToEdge: boolean;
  fitsSystemWindows: boolean;
  v31: boolean;
}

function stylesXml(v: ThemeVars, note: string): string {
  const items: string[] = [
    `<item name="android:windowLightStatusBar" tools:targetApi="23">${v.lightStatusIcons}</item>`,
    `<item name="android:windowLightNavigationBar" tools:targetApi="27">${v.lightNavIcons}</item>`,
    `<item name="android:fitsSystemWindows">${v.fitsSystemWindows}</item>`,
    `<item name="android:windowLayoutInDisplayCutoutMode" tools:targetApi="27">shortEdges</item>`,
  ];

  if (v.edgeToEdge) {
    items.unshift(
      `<item name="android:statusBarColor">${TRANSPARENT}</item>`,
      `<item name="android:navigationBarColor">${TRANSPARENT}</item>`,
      `<item name="android:windowDrawsSystemBarBackgrounds">true</item>`,
    );
    if (v.v31) {
      // Android 12+ uses the WindowInsetsController contrast enforcement.
      items.push(
        `<item name="android:enforceStatusBarContrast" tools:targetApi="29">false</item>`,
        `<item name="android:enforceNavigationBarContrast" tools:targetApi="29">false</item>`,
      );
    } else {
      // Pre-Android-12 attributes only. Never mix them with the v31 set.
      items.push(
        `<item name="android:windowTranslucentStatus">true</item>`,
        `<item name="android:windowTranslucentNavigation">true</item>`,
      );
    }
  } else {
    items.unshift(
      `<item name="android:statusBarColor">${v.statusBarColor}</item>`,
      `<item name="android:navigationBarColor">${v.navigationBarColor}</item>`,
      `<item name="android:windowDrawsSystemBarBackgrounds">true</item>`,
    );
    items.push(
      `<item name="android:windowTranslucentStatus">false</item>`,
      `<item name="android:windowTranslucentNavigation">false</item>`,
    );
    if (v.v31) {
      items.push(
        `<item name="android:enforceStatusBarContrast" tools:targetApi="29">false</item>`,
        `<item name="android:enforceNavigationBarContrast" tools:targetApi="29">false</item>`,
      );
    }
  }

  const body = items.map((i) => `        ${i}`).join("\n");
  return `${header(note)}
<resources xmlns:tools="http://schemas.android.com/tools">
    <style name="AppTheme" parent="Theme.AppCompat.DayNight.NoActionBar">
${body}
    </style>
    <style name="AppTheme.NoActionBar" parent="AppTheme">
        <item name="windowActionBar">false</item>
        <item name="windowNoTitle">true</item>
    </style>
    <style name="AppTheme.NoActionBarLaunch" parent="AppTheme.NoActionBar">
        <item name="android:background">@drawable/splash</item>
    </style>
</resources>
`;
}

/** All four resource folders for the selected mode. */
export function androidStyleFiles(
  spec: DisplayModeSpec,
  cfg: DisplayModeConfig,
): { path: string; content: string; reason: string }[] {
  const edge = spec.overlaysWebView;
  const lightIconsLight = cfg.lightModeIconStyle === "DARK"; // DARK icons => windowLightStatusBar true

  const light = (v31: boolean) =>
    stylesXml(
      {
        statusBarColor: cfg.lightStatusBarColor,
        navigationBarColor: cfg.lightNavigationBarColor,
        lightStatusIcons: lightIconsLight,
        lightNavIcons: lightIconsLight,
        edgeToEdge: edge,
        fitsSystemWindows: spec.fitsSystemWindows,
        v31,
      },
      v31 ? "Android 12+ light theme" : "light theme",
    );

  const dark = (v31: boolean) =>
    stylesXml(
      {
        statusBarColor: cfg.darkStatusBarColor,
        navigationBarColor: cfg.darkNavigationBarColor,
        lightStatusIcons: false, // dark mode is always LIGHT icons
        lightNavIcons: false,
        edgeToEdge: edge,
        fitsSystemWindows: spec.fitsSystemWindows,
        v31,
      },
      v31 ? "Android 12+ dark theme" : "dark theme",
    );

  return [
    { path: "android/app/src/main/res/values/styles.xml", content: light(false), reason: "System bars — Android 11 and below, light theme" },
    { path: "android/app/src/main/res/values-night/styles.xml", content: dark(false), reason: "System bars — Android 11 and below, dark theme" },
    { path: "android/app/src/main/res/values-v31/styles.xml", content: light(true), reason: "System bars — Android 12+, light theme" },
    { path: "android/app/src/main/res/values-night-v31/styles.xml", content: dark(true), reason: "System bars — Android 12+, dark theme" },
  ];
}

export function androidColorFiles(
  cfg: DisplayModeConfig,
): { path: string; content: string; reason: string }[] {
  const colors = (status: string, nav: string, note: string) => `${header(note)}
<resources>
    <color name="nf_status_bar">${status}</color>
    <color name="nf_navigation_bar">${nav}</color>
</resources>
`;
  return [
    { path: "android/app/src/main/res/values/colors.xml", content: colors(cfg.lightStatusBarColor, cfg.lightNavigationBarColor, "light system bar colours"), reason: "System bar colours (light)" },
    { path: "android/app/src/main/res/values-night/colors.xml", content: colors(cfg.darkStatusBarColor, cfg.darkNavigationBarColor, "dark system bar colours"), reason: "System bar colours (dark)" },
  ];
}

