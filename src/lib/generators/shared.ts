// Common files every Android project needs
export const getSharedFiles = (config: GeneratorConfig): GeneratedFile[] => {
  const files: GeneratedFile[] = [
    { path: "gradle/wrapper/gradle-wrapper.properties", content: gradleWrapperProperties() },
    { path: "gradlew", content: gradlewScript() },
    { path: "gradlew.bat", content: gradlewBatScript() },
    { path: "gradle.properties", content: gradleProperties() },
    { path: "local.properties", content: localProperties() },
    { path: "app/proguard-rules.pro", content: proguardRules() },
    { path: "app/src/main/res/values/strings.xml", content: stringsXml(config.appName, config.packageName) },
    { path: "app/src/main/res/xml/file_paths.xml", content: filePathsXml() },
    { path: "app/src/main/res/drawable/splash_screen.xml", content: splashDrawable() },
    { path: `README.md`, content: generateReadme(config) },
  ];

  // Add icon files if provided, otherwise generate a default adaptive icon
  if (config.icons && config.icons.length > 0) {
    for (const icon of config.icons) {
      files.push({
        path: `app/src/main/res/${icon.folder}/ic_launcher.png`,
        content: icon.squareBlob,
        isBinary: true,
      });
      files.push({
        path: `app/src/main/res/${icon.folder}/ic_launcher_round.png`,
        content: icon.roundBlob,
        isBinary: true,
      });
    }
  } else {
    // Generate fallback PNG icons in all density folders so @mipmap/ic_launcher resolves on all API levels
    const placeholderPng = createPlaceholderPng();
    const densityFolders = ["mipmap-mdpi", "mipmap-hdpi", "mipmap-xhdpi", "mipmap-xxhdpi"];
    for (const folder of densityFolders) {
      files.push({ path: `app/src/main/res/${folder}/ic_launcher.png`, content: placeholderPng, isBinary: true });
      files.push({ path: `app/src/main/res/${folder}/ic_launcher_round.png`, content: placeholderPng, isBinary: true });
    }

    // Also keep adaptive icon XMLs for API 26+
    const defaultIconXml = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/colorPrimary"/>
    <foreground android:drawable="@color/colorPrimary"/>
</adaptive-icon>
`;
    files.push({ path: "app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml", content: defaultIconXml });
    files.push({ path: "app/src/main/res/mipmap-anydpi-v26/ic_launcher_round.xml", content: defaultIconXml });
  }

  return files;
};

