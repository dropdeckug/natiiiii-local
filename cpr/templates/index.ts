/** Vite entry that bridges a plain-HTML project into the Vite build system. */
export function staticBridgeEntry(pages: string[]): string {
  return `// Generated by NativeForge CPR — bridges plain HTML pages into the Vite build.
const PAGES = ${JSON.stringify(pages, null, 2)};

export function resolvePage(pathname: string): string {
  const clean = pathname.replace(/^[.#/]+/, '') || 'index.html';
  return PAGES.includes(clean) ? clean : PAGES[0];
}

export default PAGES;
`;
}

